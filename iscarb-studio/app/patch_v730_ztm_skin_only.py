BG_BASE = "#FFFFFF"
BG_SURFACE = "#F8FAFC"
TEXT_HEADING = "#0F172A"
TEXT_BODY = "#475569"
ACCENT_PRIMARY = "#4F46E5"
ACCENT_CYAN = "#06B6D4"
ALERT_URGENT = "#F43F5E"
